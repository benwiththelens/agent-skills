/**
 * Load the Graphify global graph and extract the dependency subgraph for a repo.
 * Handles flexible node shapes: { id|path|file, repo, ... } and edges
 * as { edges: [...] } or { relationships: [...] } with source/target/from/to.
 */
function buildGraphifyBlock(repoPath) {
  const candidates = [
    GRAPH_PATH,
    join(WORKSPACE, repoPath, 'graphify-out/.graphify_analysis.json'),
    join(WORKSPACE, 'sovereign-cut-co/graphify-out/.graphify_analysis.json')
  ];

  let graphPathFound = null;
  for (const p of candidates) {
    if (p && existsSync(p)) {
      graphPathFound = p;
      break;
    }
  }

  if (!graphPathFound) {
    log('info', 'Graphify graph not found in candidate paths — skipping context enrichment');
    return '';
  }

  let graph;
  try {
    graph = JSON.parse(readFileSync(graphPathFound, 'utf8'));
    log('info', `Loaded Graphify context from ${graphPathFound}`);
  } catch (e) {
    log('warn', `Failed to parse Graphify graph at ${graphPathFound}: ${e.message}`);
    return '';
  }

  const nodes = Array.isArray(graph) ? graph : (graph.nodes || graph.files || []);
  const edges = graph.edges || graph.relationships || graph.links || [];
  const repoKey = repoPath.toLowerCase();

  const nodeRepo = (n) => (n.repo || n.repo_path || n.repository || '').toLowerCase();
  const nodePath = (n) => n.path || n.file || n.id || n.name || '';

  // Match nodes belonging to this repo: explicit repo field, or path prefix heuristic
  const matched = nodes.filter(n => {
    const r = nodeRepo(n);
    if (r && (r === repoKey || r.endsWith('/' + repoKey) || r.includes(repoKey))) return true;
    const p = nodePath(n).toLowerCase();
    return !r && (p.startsWith(repoKey + '/') || p.includes('/' + repoKey + '/'));
  });

  if (matched.length === 0) {
    log('info', `Graphify: no nodes matched repo '${repoPath}' — no enrichment applied`);
    return '';
  }

  const matchedIds = new Set(matched.map(n => n.id || nodePath(n)));
  const matchedEdges = edges.filter(e => {
    const s = String(e.source ?? e.from ?? '').toLowerCase();
    const t = String(e.target ?? e.to ?? '').toLowerCase();
    return [...matchedIds].some(id => s.includes(String(id).toLowerCase()) || t.includes(String(id).toLowerCase()));
  });

  const lines = [];
  lines.push('');
  lines.push('## Graphify Codebase Dependency Subgraph');
  lines.push(`Repository: \`${repoPath}\` — ${matched.length} indexed file(s), ${matchedEdges.length} known relationship(s).`);
  lines.push('');
  lines.push('### Indexed Files');
  for (const n of matched.slice(0, 120)) {
    const kind = n.kind || n.type || 'file';
    const lang = n.language || n.lang || '';
    lines.push(`- \`${nodePath(n)}\` (${kind}${lang ? ', ' + lang : ''})`);
  }
  if (matched.length > 120) lines.push(`- ...and ${matched.length - 120} more (truncated)`);

  if (matchedEdges.length > 0) {
    lines.push('');
    lines.push('### AST Relationships');
    for (const e of matchedEdges.slice(0, 150)) {
      const s = e.source ?? e.from;
      const t = e.target ?? e.to;
      const rel = e.type || e.kind || e.relationship || 'depends-on';
      lines.push(`- \`${s}\` —[${rel}]→ \`${t}\``);
    }
    if (matchedEdges.length > 150) lines.push(`- ...and ${matchedEdges.length - 150} more (truncated)`);
  }

  log('info', `Graphify enrichment: ${matched.length} nodes, ${matchedEdges.length} edges for '${repoPath}'`);
  return lines.join('\n');
}

