#!/usr/bin/env node
/**
 * jules-queue-dispatcher.mjs
 * Next-Gen Jules Queue Dispatcher & Spec Enricher.
 *
 * Reads pending task specs from the vault queue, enriches prompts with the
 * Graphify codebase dependency subgraph, dispatches to the Jules API,
 * tracks state + daily rate limits, and archives processed specs.
 *
 * Orchestrated by VANTAGE co-pilot on Cato.
 *
 * STRICT ARCHITECT PR APPROVAL POLICY:
 *   - Jules sessions may open Pull Requests, but PRs must NEVER be
 *     auto-merged into `main`. Every PR is recorded in state as
 *     `AWAITING_ARCHITECT_APPROVAL` and requires Ben's manual review
 *     & approval on GitHub before merging.
 *
 * Usage:
 *   node jules-queue-dispatcher.mjs [--dry-run] [--limit N] [--verbose]
 *   node jules-queue-dispatcher.mjs --digest [--send]
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, renameSync, statSync } from 'fs';
import { join, basename } from 'path';
import { createSession, listSources } from './jules-client.mjs';
import { sendDiscordAlert } from './jules-discord.mjs';

// ==========================================
// Configuration
// ==========================================
const WORKSPACE = '/home/node/.openclaw/workspace';
const QUEUE_DIR = join(WORKSPACE, 'vault/01-ACTIVE/jules-queue');
const PROCESSED_DIR = join(QUEUE_DIR, 'processed');
const STATE_PATH = join(WORKSPACE, 'jules-state.json');
const GRAPH_PATH = '/home/node/.graphify/global-graph.json';

const DAILY_HARD_LIMIT = 100; // Google's hard cap
const MANUAL_RESERVE_BUFFER = 20; // Reserved strictly for Ben's manual on-demand sessions
const DAILY_SAFETY_LIMIT = DAILY_HARD_LIMIT - MANUAL_RESERVE_BUFFER; // 80 automated background cap
const HISTORY_CAP = 200; // Max dispatch history entries retained in state
const STATE_SCHEMA_VERSION = 2;

// ==========================================
// Strict Architect PR Approval Policy
// ==========================================
// Jules opens PRs via AUTO_CREATE_PR, but merging is ALWAYS manual.
// There is intentionally no merge/automerge code path anywhere in the
// Jules pipeline. This flag exists as a hard circuit breaker: it must
// never be set to true.
const PR_AUTO_MERGE_ENABLED = false;
const PR_STATUS_AWAITING = 'AWAITING_ARCHITECT_APPROVAL';

/**
 * Circuit breaker: abort the process if anything ever attempts to
 * enable PR auto-merge. PRs generated by Jules require Ben's manual
 * review & approval before merging — no exceptions.
 */
function assertNoAutoMerge() {
  if (PR_AUTO_MERGE_ENABLED !== false) {
    throw new Error('POLICY VIOLATION: Jules PR auto-merge is permanently disabled by the Strict Architect PR Approval Policy.');
  }
}

const args = process.argv.slice(2);
const DRY_RUN = args.includes('--dry-run');
const VERBOSE = args.includes('--verbose');
const DIGEST_MODE = args.includes('--digest');
const DIGEST_SEND = args.includes('--send');
const LIMIT_IDX = args.indexOf('--limit');
const RUN_LIMIT = LIMIT_IDX !== -1 ? parseInt(args[LIMIT_IDX + 1], 10) : Infinity;

// ==========================================
// Structured Logging
// ==========================================
function log(level, msg, data) {
  const ts = new Date().toISOString();
  const line = `[${ts}] [${level.toUpperCase()}] [JulesDispatcher] ${msg}`;
  if (data !== undefined) {
    console.log(line, typeof data === 'string' ? data : JSON.stringify(data));
  } else {
    console.log(line);
  }
}

