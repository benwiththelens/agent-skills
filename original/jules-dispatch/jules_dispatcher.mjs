/**
 * Compile the daily Jules pipeline digest.
 *
 * Summarizes:
 *   - sessions dispatched today (America/Chicago)
 *   - rate limit status (X / 90 safety ceiling used)
 *   - active Jules PRs awaiting Architect approval
 *   - completed jobs
 *
 * @param {object} [opts]
 * @param {boolean} [opts.send=false] - also push the digest to Discord
 * @returns {Promise<string>} the formatted digest text
 */
export async function generateDailyDigest(opts = {}) {
  const state = loadState();
  const today = chicagoToday();
  const usedToday = state.dispatch.daily[today] || 0;

  // Sessions dispatched today (prefer the recorded Chicago day stamp)
  const todaysDispatches = state.dispatch.history.filter(h =>
    h.day === today || (!h.day && typeof h.dispatchedAt === 'string' && h.dispatchedAt.startsWith(today))
  );

  // PRs awaiting Architect approval (never auto-merged)
  const pendingPrs = Object.values(state.prs || {}).filter(p => p.status === PR_STATUS_AWAITING);

  // Completed jobs tracked in state
  const completedSessions = Object.entries(state.sessions || {})
    .filter(([, s]) => (typeof s === 'object' ? s.state : s) === 'COMPLETED');

  const lines = [];
  lines.push(`📋 **Jules Daily Digest — ${today}**`);
  lines.push(`> **Dispatched today:** ${todaysDispatches.length} session(s)`);
  for (const h of todaysDispatches.slice(-10)) {
    lines.push(`>   • \`${h.repo}\` — ${h.title || h.spec} (\`${h.sessionId}\`)`);
  }
  lines.push(`> **Rate limit:** ${usedToday} / ${DAILY_SAFETY_LIMIT} used (${Math.max(0, DAILY_SAFETY_LIMIT - usedToday)} remaining for auto queue; ${MANUAL_RESERVE_BUFFER} sessions reserved for Ben's manual jobs)`);
  lines.push(`> **PRs awaiting Architect approval:** ${pendingPrs.length}`);
  for (const pr of pendingPrs.slice(0, 15)) {
    lines.push(`>   • [${pr.title || 'Pull Request'}](${pr.url}) — \`${pr.repo}\` (session \`${pr.sessionId}\`)`);
  }
  if (pendingPrs.length > 15) lines.push(`>   • ...and ${pendingPrs.length - 15} more`);
  lines.push(`> **Completed jobs:** ${completedSessions.length}`);
  lines.push(`\n*Auto-merge is disabled. All PRs require Ben's manual review & approval before merging to \`main\`.*`);

  const digest = lines.join('\n');
  console.log(digest);

  // Archive digest to the vault for autonomous Librarian indexing
  try {
    const digestDir = join(WORKSPACE, 'vault/01-ACTIVE/syntheses/jules-digests');
    if (!existsSync(digestDir)) {
      mkdirSync(digestDir, { recursive: true });
    }
    const vaultDigestPath = join(digestDir, `Jules-Daily-Digest-${today}.md`);
    const markdownContent = `# 📋 Jules Daily Digest — ${today}\n\n**Date:** ${today}\n**Generated By:** VANTAGE Jules Queue Pipeline\n\n${digest}\n`;
    writeFileSync(vaultDigestPath, markdownContent, 'utf8');
    log('info', `Saved Daily Digest to vault: ${vaultDigestPath}`);
  } catch (err) {
    log('error', `Failed to write Daily Digest to vault: ${err.message}`);
  }

  if (opts.send) {
    await sendDiscordAlert(digest);
  }
  return digest;
}

// ==========================================
// Main Dispatch Flow
// ==========================================

async function main() {
  // Strict Architect PR Approval Policy — hard circuit breaker, always on.
  assertNoAutoMerge();

  // Digest mode: compile (and optionally broadcast) the daily summary, then exit.
  if (DIGEST_MODE) {
    await generateDailyDigest({ send: DIGEST_SEND && !DRY_RUN });
    return;
  }

  log('info', `Starting queue sweep${DRY_RUN ? ' (DRY RUN)' : ''} — limit: ${RUN_LIMIT === Infinity ? 'none' : RUN_LIMIT}, daily safety cap: ${DAILY_SAFETY_LIMIT}/${DAILY_HARD_LIMIT}`);

  // Ensure queue directories exist
  for (const dir of [QUEUE_DIR, PROCESSED_DIR]) {
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
      log('info', `Created missing directory: ${dir}`);
    }
  }

  // Collect pending specs
  const specs = readdirSync(QUEUE_DIR)
    .filter(f => f.endsWith('.md') && statSync(join(QUEUE_DIR, f)).isFile())
    .map(f => {
      const full = join(QUEUE_DIR, f);
      const raw = readFileSync(full, 'utf8');
      const meta = parseSpecMetadata(raw);
      return { file: f, path: full, raw, meta, mtime: statSync(full).mtimeMs };
    })
    .filter(s => {
      if (!s.meta.repo_path) {
        log('warn', `Skipping '${s.file}' — missing required 'repo_path' metadata`);
        return false;
      }
      return true;
    })
    .sort((a, b) => priorityRank(a.meta.priority) - priorityRank(b.meta.priority) || a.mtime - b.mtime);

  if (specs.length === 0) {
    log('info', 'Queue is empty. Nothing to dispatch.');
    return;
  }
  log('info', `Found ${specs.length} pending spec(s): ${specs.map(s => s.file).join(', ')}`);

  // Rate limit check
  const state = loadState();
  const today = chicagoToday();
  let dispatchedToday = dailyCount(state);
  log('info', `Daily dispatch counter (${today}, America/Chicago): ${dispatchedToday}/${DAILY_SAFETY_LIMIT}`);

  if (dispatchedToday >= DAILY_SAFETY_LIMIT) {
    log('warn', `Daily safety limit reached (${dispatchedToday}/${DAILY_SAFETY_LIMIT}). Halting to stay below Google's ${DAILY_HARD_LIMIT}/day hard cap.`);
    return;
  }

  // Resolve Jules sources once
  let sourceMap;
  try {
    sourceMap = await resolveSources();
    log('info', `Resolved ${sourceMap.size} connected Jules source(s)`);
    if (VERBOSE) log('debug', 'Sources:', [...sourceMap.keys()]);
  } catch (e) {
    log('error', `Failed to list Jules sources: ${e.message}`);
    process.exit(1);
  }

  let dispatched = 0;
  for (const spec of specs) {
    if (dispatched >= RUN_LIMIT) {
      log('info', `Run limit reached (--limit ${RUN_LIMIT}). Stopping.`);
      break;
    }
    if (dispatchedToday >= DAILY_SAFETY_LIMIT) {
      log('warn', `Daily safety limit hit mid-run (${dispatchedToday}/${DAILY_SAFETY_LIMIT}). Remaining specs stay queued.`);
      break;
    }

    const { repo_path, title, priority, branch } = spec.meta;
    const sourceObj = sourceMap.get(repo_path.toLowerCase());
    if (!sourceObj) {
      log('error', `No Jules source matches repo_path '${repo_path}' for '${spec.file}' — leaving in queue`);
      continue;
    }

    const source = typeof sourceObj === 'string' ? sourceObj : sourceObj.name;
    const defaultBranch = (typeof sourceObj === 'object' && sourceObj.defaultBranch) ? sourceObj.defaultBranch : 'main';
    const targetBranch = branch || defaultBranch;

    // Build enriched prompt
    let body = stripFrontmatter(spec.raw);
    // Strip local vault references so Jules is not confused by paths outside the Git repo
    body = body
      .replace(/>\s*\*\*Queue Location:\*\*\s*`[^`]+`\r?\n?/gi, '')
      .replace(/Queue Location:\s*vault\/[^\n]+\n?/gi, '')
      .trim();

    const graphBlock = buildGraphifyBlock(repo_path);
    const prompt = `${body}${graphBlock ? '\n\n' + graphBlock : ''}`.trim();
    const sessionTitle = title || basename(spec.file, '.md');

    log('info', `Dispatching '${spec.file}' → ${source} [priority=${priority || 'medium'}]`);
    if (VERBOSE) log('debug', `Prompt preview (first 300 chars): ${prompt.slice(0, 300)}`);

    if (DRY_RUN) {
      log('info', `[DRY RUN] Would create session '${sessionTitle}' on ${source}${graphBlock ? ' with Graphify enrichment' : ''}`);
      dispatched++;
      continue;
    }

    try {
      // AUTO_CREATE_PR opens a PR for review only. Merging is ALWAYS
      // manual (Ben / Architect) — there is no auto-merge code path.
      const session = await createSession(source, prompt, {
        title: sessionTitle,
        startingBranch: targetBranch,
        automationMode: 'AUTO_CREATE_PR',
        requirePlanApproval: false
      });

      const sessionId = (session.name || '').replace('sessions/', '') || session.id || 'unknown';
      dispatched++;
      dispatchedToday++;

      // Update state ledger
      state.dispatch.daily[today] = dispatchedToday;
      state.dispatch.history.push({
        spec: spec.file,
        repo: repo_path,
        source,
        sessionId,
        title: sessionTitle,
        priority: priority || 'medium',
        graphifyEnriched: Boolean(graphBlock),
        day: today,
        dispatchedAt: new Date().toISOString()
      });
      state.sessions[sessionId] = {
        state: 'QUEUED',
        orchestrated: false,
        spec: spec.file,
        repo: repo_path,
        title: sessionTitle,
        prPolicy: PR_STATUS_AWAITING,
        dispatchedAt: new Date().toISOString()
      };
      saveState(state);

      // Move spec to processed/
      const dest = join(PROCESSED_DIR, spec.file);
      renameSync(spec.path, dest);
      log('info', `✅ Session ${sessionId} created for '${spec.file}' → archived to processed/`);

      // Per-job Discord notification (failures must not break the sweep)
      try {
        let alertText = `🚀 **[Jules Job Dispatched]**\n`;
        alertText += `> **Repo:** \`${repo_path}\`\n`;
        alertText += `> **Session:** \`${sessionId}\`\n`;
        alertText += `> **Task:** *${sessionTitle}*\n`;
        alertText += `> **Priority:** \`${priority || 'medium'}\` | **Daily usage:** ${dispatchedToday}/${DAILY_SAFETY_LIMIT}\n`;
        alertText += `*Any PR opened will be held as \`${PR_STATUS_AWAITING}\` — Ben's manual review & approval required before merging.*`;
        await sendDiscordAlert(alertText);
      } catch (notifyErr) {
        log('warn', `Discord dispatch notification failed for '${spec.file}': ${notifyErr.message}`);
      }

      // Gentle pacing between API writes to respect rate limits
      await new Promise(r => setTimeout(r, 1500));
    } catch (e) {
      log('error', `Dispatch failed for '${spec.file}': ${e.message} — leaving in queue`);
    }
  }

  log('info', `Sweep complete. Dispatched: ${dispatched}. Daily total: ${dispatchedToday}/${DAILY_SAFETY_LIMIT}. Remaining in queue: ${specs.length - dispatched}.`);
}

main().catch(e => {
  log('error', `Fatal dispatcher failure: ${e.message}`);
  process.exit(1);
});
