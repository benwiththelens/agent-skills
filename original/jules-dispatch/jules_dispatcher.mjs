/** Current date in America/Chicago (YYYY-MM-DD) for the daily counter. */
function chicagoToday() {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Chicago',
    year: 'numeric', month: '2-digit', day: '2-digit'
  }).format(new Date());
}

/**
 * Minimal frontmatter / header metadata parser (zero-dependency).
 * Supports:
 *   ---
 *   repo_path: ez-boat-numbers
 *   title: Fix the thing
 *   priority: high
 *   ---
 * or bare `key: value` lines in the first ~30 lines of the file.
 */
function parseSpecMetadata(raw) {
  const meta = {};
  const lines = raw.split('\n');

  // YAML-style frontmatter block
  if (lines[0] && lines[0].trim() === '---') {
    for (let i = 1; i < lines.length; i++) {
      const l = lines[i].trim();
      if (l === '---') break;
      const m = l.match(/^([A-Za-z0-9_\-]+)\s*:\s*(.+)$/);
      if (m) meta[m[1].toLowerCase().trim()] = m[2].trim().replace(/^["']|["']$/g, '');
    }
  } else {
    // Bare header metadata scan (first 30 non-body lines)
    for (let i = 0; i < Math.min(lines.length, 30); i++) {
      const l = lines[i].trim();
      if (l.startsWith('#')) {
        // Treat first H1 as title fallback
        if (!meta.title) meta.title = l.replace(/^#+\s*/, '').trim();
        continue;
      }
      const m = l.match(/^([A-Za-z0-9_\-]+)\s*:\s*(.+)$/);
      if (m && ['repo_path', 'repo', 'title', 'priority', 'branch', 'startingbranch'].includes(m[1].toLowerCase())) {
        meta[m[1].toLowerCase().trim()] = m[2].trim().replace(/^["']|["']$/g, '');
      }
    }
  }

  if (meta.repo && !meta.repo_path) meta.repo_path = meta.repo;
  if (meta.startingbranch && !meta.branch) meta.branch = meta.startingbranch;
  return meta;
}

/** Strip the frontmatter block (and bare header metadata) so the prompt is clean. */
function stripFrontmatter(raw) {
  const lines = raw.split('\n');
  if (lines[0] && lines[0].trim() === '---') {
    for (let i = 1; i < lines.length; i++) {
      if (lines[i].trim() === '---') return lines.slice(i + 1).join('\n').trim();
    }
  }
  // Bare header form: drop `key: value` metadata lines and keep prose/headings
  return lines
    .filter(l => {
      const m = l.trim().match(/^([A-Za-z0-9_\-]+)\s*:\s*(.+)$/);
      return !(m && ['repo_path', 'repo', 'title', 'priority', 'branch', 'startingbranch'].includes(m[1].toLowerCase()));
    })
    .join('\n')
    .trim();
}

/** Priority rank for sorting (lower = sooner). */
function priorityRank(p) {
  const v = (p || 'medium').toLowerCase();
  if (v === 'critical' || v === 'urgent' || v === 'p0') return 0;
  if (v === 'high' || v === 'p1') return 1;
  if (v === 'medium' || v === 'normal' || v === 'p2') return 2;
  if (v === 'low' || v === 'p3') return 3;
  const n = parseInt(v, 10);
  return Number.isNaN(n) ? 2 : n;
}

