/** Resolve a repo_path (e.g. "Fabrik8OS") to a Jules source name. */
async function resolveSources() {
  const res = await listSources();
  const sources = res.sources || [];
  const map = new Map(); // lowercase repo name -> { name, defaultBranch }
  for (const s of sources) {
    const repo = s.githubRepo?.repo || s.name.split('/').pop();
    const defaultBranch = s.githubRepo?.defaultBranch?.displayName || 'main';
    if (repo) map.set(repo.toLowerCase(), { name: s.name, defaultBranch });
  }
  return map;
}

// ==========================================
// State Tracking
// ==========================================

/** Fresh v2 state schema. */
function emptyState() {
  return {
    version: STATE_SCHEMA_VERSION,
    sessions: {},
    dispatch: { daily: {}, history: [] },
    prs: {} // PR url -> { status, url, title, repo, sessionId, recordedAt }
  };
}

/** Load state and migrate older schemas forward to v2. */
function loadState() {
  if (!existsSync(STATE_PATH)) return emptyState();
  try {
    const state = JSON.parse(readFileSync(STATE_PATH, 'utf8'));
    if (!state.sessions) state.sessions = {};
    if (!state.dispatch) state.dispatch = { daily: {}, history: [] };
    if (!state.dispatch.daily) state.dispatch.daily = {};
    if (!state.dispatch.history) state.dispatch.history = [];
    if (!state.prs) state.prs = {}; // v1 -> v2 migration
    state.version = STATE_SCHEMA_VERSION;
    return state;
  } catch (e) {
    log('warn', `State file corrupt, starting fresh dispatch ledger: ${e.message}`);
    return emptyState();
  }
}

function saveState(state) {
  // Cap history
  if (state.dispatch.history.length > HISTORY_CAP) {
    state.dispatch.history = state.dispatch.history.slice(-HISTORY_CAP);
  }
  const tmp = STATE_PATH + '.tmp';
  writeFileSync(tmp, JSON.stringify(state, null, 2));
  renameSync(tmp, STATE_PATH);
}

function dailyCount(state) {
  return state.dispatch.daily[chicagoToday()] || 0;
}

